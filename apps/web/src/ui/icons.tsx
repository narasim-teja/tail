// Game concepts use the brand's icons (@tail/brand, 24-grid, currentColor); lucide stays for
// generic controls (play, pause, close).

import { type IconName, icons, markSvg } from "@tail/brand";
import { cn } from "@/lib/utils";
import { statusLabel } from "../replay/copy.ts";
import type { VerdictStatus } from "../verify/report.ts";
import { type Glyph, STATUS_GLYPH } from "./marks.ts";

export function GameIcon({ name, className, label }: { name: IconName; className?: string; label?: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cn("size-4 shrink-0", className)}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      // biome-ignore lint/security/noDangerouslySetInnerHtml: static path data from @tail/brand, never user input
      dangerouslySetInnerHTML={{ __html: icons[name] }}
    />
  );
}

/** The Trail mark, the page's signature. */
export function TrailMark({ className, color }: { className?: string; color?: string }) {
  return (
    <span
      className={cn("inline-block shrink-0 [&>svg]:size-full", className)}
      aria-hidden="true"
      // biome-ignore lint/security/noDangerouslySetInnerHtml: generated by @tail/brand from constants
      dangerouslySetInnerHTML={{ __html: markSvg(color ? { color } : {}) }}
    />
  );
}

/** Draws one glyph from marks.ts. Colour carries emphasis; the shape carries the meaning. */
export function GlyphIcon({ glyph, className, label }: { glyph: Glyph; className?: string; label?: string }) {
  if (glyph === "check")
    return <GameIcon name="verified" {...(label ? { label } : {})} className={cn("text-text", className)} />;
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={glyph === "bar" ? 2 : 1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      data-glyph={glyph}
      className={cn(
        "size-4 shrink-0",
        glyph === "bar" ? "text-text" : glyph === "tick" ? "text-text-2" : "text-text-3",
        className,
      )}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {glyph === "tick" ? (
        <path d="M6.5 12.5 L10.2 16.2 L17.5 8.2" />
      ) : glyph === "earlier" ? (
        <>
          <path d="M3.5 13.5 L7 17 L13 10.5" />
          <circle cx="17.5" cy="7.5" r="4" />
          <path d="M17.5 5.5 V7.5 L19 8.5" />
        </>
      ) : (
        <circle cx="12" cy="12" r="9" strokeDasharray={glyph === "dashed" ? "2 3.2" : undefined} />
      )}
      {glyph === "bar" && <path d="M7.5 12h9" />}
    </svg>
  );
}

/**
 * The one verification mark, identical in the header, the timeline, the event line and the
 * sheet. Its shape comes from STATUS_GLYPH: the ringed check only when the event matches NEAR.
 */
export function Mark({
  status,
  className,
  labelled = true,
}: {
  status: VerdictStatus;
  className?: string;
  labelled?: boolean;
}) {
  const label = labelled ? statusLabel[status] : undefined;
  return (
    <GlyphIcon
      glyph={STATUS_GLYPH[status]}
      {...(className ? { className } : {})}
      {...(label ? { label } : {})}
    />
  );
}
