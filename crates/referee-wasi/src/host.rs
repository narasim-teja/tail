//! Everything the referee asks of its host: input and output, who is calling, the call id,
//! randomness, the verdict key, the state key, storage, the VRF, clocks and the author's
//! secrets. Kept in one place so the rest of the crate is plain data handling.
//!
//! Two backends export the same functions, chosen by target, so command code never forks:
//! - `enclave` (wasm): the OutLayer worker, the deployed referee.
//! - `local` (native): the local test referee, a plain process with its keys on disk. It is
//!   not an enclave, and matches it judges are test-referee matches.

#[cfg(target_family = "wasm")]
mod enclave;
#[cfg(target_family = "wasm")]
pub use enclave::*;

#[cfg(not(target_family = "wasm"))]
mod local;
#[cfg(not(target_family = "wasm"))]
pub use local::*;

/// Storage record of the referee's X25519 box secret.
const BOX_SK_RECORD: &str = "referee:box_sk";

#[derive(Debug)]
pub struct Vrf {
    pub alpha: String,
    pub signature: [u8; 64],
}

/// The referee's X25519 box secret: generated by the referee on first use and kept in its
/// storage (the owner's encrypted cell on OutLayer). `set_if_absent` makes two first calls
/// agree on one key.
pub fn box_sk() -> Result<[u8; 32], String> {
    let stored = if let Some(v) = storage_get(BOX_SK_RECORD)? {
        v
    } else {
        let fresh: [u8; 32] = random();
        if storage_set_if_absent(BOX_SK_RECORD, &fresh)? {
            return Ok(fresh);
        }
        storage_get(BOX_SK_RECORD)?.ok_or("box key vanished between two reads")?
    };
    stored
        .try_into()
        .map_err(|v: Vec<u8>| format!("stored box key is {} bytes, expected 32", v.len()))
}
